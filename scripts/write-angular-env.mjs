import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const values = {};

for (const file of ['.env', 'src/.env']) {
  try {
    const contents = await readFile(resolve(root, file), 'utf8');
    for (const line of contents.split(/\r?\n/)) {
      const match = /^([^#=\s]+)\s*=\s*(.*)$/.exec(line);
      if (match) values[match[1]] = match[2].replace(/^['"]|['"]$/g, '');
    }
  } catch {
    // A checked-in environment file is optional; CI can provide environment variables.
  }
}

const supabaseUrl = process.env['VITE_SUPABASE_URL'] ?? values['VITE_SUPABASE_URL'] ?? '';
const supabaseKey =
  process.env['VITE_SUPABASE_PUBLISHABLE_KEY'] ?? values['VITE_SUPABASE_PUBLISHABLE_KEY'] ?? '';

const environmentDirectory = resolve(root, 'src/environments');
await mkdir(environmentDirectory, { recursive: true });

await writeFile(
  resolve(environmentDirectory, 'environment.generated.ts'),
  `// Generated by scripts/write-angular-env.mjs. Do not commit credentials.\n` +
    `export const environment = ${JSON.stringify({ supabaseUrl, supabaseKey }, null, 2)} as const;\n`,
);
